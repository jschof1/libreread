package com.github.libretube.reader

import android.app.Activity
import android.content.Context
import android.graphics.Bitmap
import android.os.SystemClock
import androidx.core.content.edit
import androidx.test.platform.app.InstrumentationRegistry
import androidx.test.runner.lifecycle.ActivityLifecycleMonitorRegistry
import androidx.test.runner.lifecycle.Stage
import com.github.libretube.reader.model.ArticleContent
import com.github.libretube.reader.model.ArticleRecord
import com.github.libretube.reader.model.ArticleSection
import com.github.libretube.reader.model.ArticleSettings
import com.github.libretube.reader.model.TranscriptRecord
import com.github.libretube.reader.model.TranscriptSegment
import com.github.libretube.reader.model.TranscriptSource
import kotlinx.coroutines.runBlocking
import java.io.File

/**
 * Deterministic fixtures for instrumentation tests. Records are written straight into the real
 * [com.github.libretube.reader.store.ArticleStore] used by the app, so no AI request is needed.
 */
object ReaderTestSupport {
    const val VIDEO_ID = "lrTest00001"
    const val ARTICLE_TITLE = "How seeded articles are rendered"
    const val TRANSCRIPT_LINE = "This is the original seeded transcript line."

    val context: Context get() = InstrumentationRegistry.getInstrumentation().targetContext

    /** Clears reader storage and points the service at an unusable host, so any AI call fails. */
    fun resetReader() {
        ReaderGraph.storeDirectory(context).deleteRecursively()
        context.getSharedPreferences(ReaderPreferences.FILE_NAME, Context.MODE_PRIVATE).edit(commit = true) {
            clear()
            putString(ReaderPreferences.KEY_API_URL, "https://libreread-test.invalid")
            putString(ReaderPreferences.KEY_DEVICE_TOKEN, "")
        }
    }

    fun seededRecord(videoId: String = VIDEO_ID, revision: String = "seed-1"): ArticleRecord {
        val sections = (1..30).map { index ->
            ArticleSection(
                heading = "Section $index",
                paragraphs = (1..3).map { p ->
                    "Paragraph $index.$p explains a detail at length so the article is long enough " +
                        "to scroll. It keeps the reasoning, the example and the qualification that " +
                        "the speaker gave, rather than reducing it to a summary line."
                }
            )
        }
        val transcript = TranscriptRecord(
            videoId = videoId,
            title = "Seeded video",
            creator = "Seed Creator",
            language = "en",
            source = TranscriptSource.CREATOR_CAPTIONS,
            autoGenerated = false,
            segments = listOf(
                TranscriptSegment(0, 2000, TRANSCRIPT_LINE),
                TranscriptSegment(2000, 4000, "A second transcript line.")
            ),
            retrievedAtMs = 1_700_000_000_000
        )
        return ArticleRecord(
            videoId = videoId,
            revision = revision,
            sourceUrl = ArticleRecord.sourceUrlFor(videoId),
            originalTitle = "Seeded video",
            creator = "Seed Creator",
            article = ArticleContent(
                title = ARTICLE_TITLE,
                sections = sections,
                visualNotes = listOf("A diagram is shown but not described in the transcript.")
            ),
            settings = ArticleSettings(),
            style = ArticleSettings().styleInstructions(),
            model = "seed-model",
            createdAtMs = 1_700_000_000_000,
            transcript = transcript
        )
    }

    fun seed(record: ArticleRecord = seededRecord()) = runBlocking {
        ReaderGraph.store(context).writeArticle(record)
    }

    /** Polls [condition] on the test thread until it holds or [timeoutMs] passes. */
    fun waitFor(timeoutMs: Long = 5_000, condition: () -> Boolean): Boolean {
        val end = SystemClock.uptimeMillis() + timeoutMs
        while (SystemClock.uptimeMillis() < end) {
            if (condition()) return true
            SystemClock.sleep(50)
        }
        return condition()
    }

    /** Saves a screenshot to the app's external files under test-artifacts for CI collection. */
    fun screenshot(name: String) {
        val instrumentation = InstrumentationRegistry.getInstrumentation()
        instrumentation.waitForIdleSync()
        // Espresso observes views before SurfaceFlinger necessarily presents their next frame.
        SystemClock.sleep(300)
        val bitmap = checkNotNull(instrumentation.uiAutomation.takeScreenshot())
        try {
            val dir = File(context.getExternalFilesDir(null), "test-artifacts").apply { mkdirs() }
            File(dir, "$name.png").outputStream().use {
                check(bitmap.compress(Bitmap.CompressFormat.PNG, 100, it))
            }
        } finally {
            bitmap.recycle()
        }
    }

    fun finishAllActivities() {
        val instrumentation = InstrumentationRegistry.getInstrumentation()
        instrumentation.runOnMainSync {
            val registry = ActivityLifecycleMonitorRegistry.getInstance()
            listOf(Stage.RESUMED, Stage.STARTED, Stage.PAUSED, Stage.STOPPED, Stage.CREATED)
                .flatMap { registry.getActivitiesInStage(it) }
                .forEach(Activity::finish)
        }
        instrumentation.waitForIdleSync()
    }
}
