package com.github.libretube.reader.model

import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable

/**
 * Where the words of a transcript came from. The reader always labels this next to the article.
 */
@Serializable
enum class TranscriptSource {
    @SerialName("creator-captions")
    CREATOR_CAPTIONS,

    @SerialName("automatic-captions")
    AUTOMATIC_CAPTIONS,

    @SerialName("ai-transcription")
    AI_TRANSCRIPTION,

    @SerialName("user-supplied")
    USER_SUPPLIED
}

/**
 * One piece of transcript text. Timestamps are kept when the source provides them.
 */
@Serializable
data class TranscriptSegment(
    val startMs: Long? = null,
    val endMs: Long? = null,
    val text: String
)

/**
 * The source text an article is written from, with enough metadata to label it truthfully.
 */
@Serializable
data class TranscriptRecord(
    val videoId: String,
    val title: String,
    val creator: String,
    /** BCP 47 language tag reported by the source, if known. */
    val language: String? = null,
    val source: TranscriptSource,
    /** Whether the caption track was generated automatically by YouTube. */
    val autoGenerated: Boolean,
    val segments: List<TranscriptSegment>,
    /** Model that produced an AI transcription, if any. */
    val model: String? = null,
    val retrievedAtMs: Long
) {
    val hasTimestamps: Boolean get() = segments.any { it.startMs != null }

    /** The text sent to the article service. Never truncated. */
    fun plainText(): String = TranscriptText.join(segments)
}

object TranscriptText {
    /** A pause this long between timed segments starts a new paragraph. */
    const val PARAGRAPH_GAP_MS = 3_000L

    fun join(segments: List<TranscriptSegment>): String {
        val builder = StringBuilder()
        var previous: TranscriptSegment? = null
        for (segment in segments) {
            val text = segment.text.trim()
            if (text.isEmpty()) continue
            if (previous != null) {
                val gap = gapMs(previous, segment)
                when {
                    gap == null -> builder.append("\n")
                    gap >= PARAGRAPH_GAP_MS -> builder.append("\n\n")
                    else -> builder.append(' ')
                }
            }
            builder.append(text)
            previous = segment
        }
        return builder.toString()
    }

    private fun gapMs(previous: TranscriptSegment, next: TranscriptSegment): Long? {
        val start = next.startMs ?: return null
        val end = previous.endMs ?: previous.startMs ?: return null
        return start - end
    }

    /** Split pasted or server-returned text into untimed segments, one per paragraph. */
    fun untimedSegments(text: String): List<TranscriptSegment> = text
        .replace("\r\n", "\n")
        .split(Regex("\n\\s*\n"))
        .map { it.replace(Regex("\\s*\n\\s*"), " ").trim() }
        .filter { it.isNotEmpty() }
        .map { TranscriptSegment(text = it) }
}

/** Article length preference, sent as `detail`. Separate from writing style. */
@Serializable
enum class ArticleDetail(val wireName: String) {
    @SerialName("full")
    FULL("full"),

    @SerialName("balanced")
    BALANCED("balanced"),

    @SerialName("brief")
    BRIEF("brief");

    companion object {
        fun fromWire(value: String?): ArticleDetail =
            entries.firstOrNull { it.wireName == value } ?: FULL
    }
}

/** One section of an article, matching the service contract. Plain text only. */
@Serializable
data class ArticleSection(
    val heading: String,
    val paragraphs: List<String>
)

/** The validated article body returned by `POST /v1/articles`. */
@Serializable
data class ArticleContent(
    val title: String,
    val sections: List<ArticleSection>,
    val visualNotes: List<String> = emptyList()
)

/** The writing preferences an article was generated with. */
@Serializable
data class ArticleSettings(
    val stylePreset: String = StylePresets.DEFAULT.key,
    val customInstructions: String = "",
    val detail: ArticleDetail = ArticleDetail.FULL
) {
    /** The exact `style` string sent to the service. */
    fun styleInstructions(): String = StylePresets.compose(stylePreset, customInstructions)
}

/**
 * A completed, saved article. Immutable: a rewrite produces a new record with a new [revision],
 * and the article and its transcript are always written together in one atomic file.
 */
@Serializable
data class ArticleRecord(
    val schemaVersion: Int = SCHEMA_VERSION,
    val videoId: String,
    /** Changes whenever the article text changes. Reading positions are tied to it. */
    val revision: String,
    val sourceUrl: String,
    val originalTitle: String,
    val creator: String,
    val article: ArticleContent,
    val settings: ArticleSettings,
    /** The style instructions actually sent with the request. */
    val style: String,
    val model: String,
    val createdAtMs: Long,
    val transcript: TranscriptRecord
) {
    companion object {
        const val SCHEMA_VERSION = 1

        fun sourceUrlFor(videoId: String) = "https://www.youtube.com/watch?v=$videoId"
    }
}

/**
 * Where the reader stopped. Stored separately from the article and only applied when
 * [revision] matches the article being shown.
 */
@Serializable
data class ReadingPosition(
    val videoId: String,
    val revision: String,
    /** Index of the first visible rendered block. */
    val blockIndex: Int,
    /** Pixels scrolled past the top of that block. */
    val offsetPx: Int,
    /** Fraction of the article scrolled, 0..1, for list display. */
    val progress: Float,
    val updatedAtMs: Long
)

/** Lightweight listing entry for saved articles. */
data class ArticleSummary(
    val videoId: String,
    val title: String,
    val originalTitle: String,
    val creator: String,
    val source: TranscriptSource,
    val createdAtMs: Long,
    val progress: Float?
)
