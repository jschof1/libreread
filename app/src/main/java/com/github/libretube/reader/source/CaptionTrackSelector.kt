package com.github.libretube.reader.source

import java.util.Locale

/** A caption track offered by the content source. */
data class CaptionTrack(
    val url: String,
    val mimeType: String?,
    val language: String?,
    val name: String?,
    val autoGenerated: Boolean
)

/**
 * Orders caption tracks by preference: creator captions in the preferred language, then automatic
 * captions in that language, then English creator and automatic captions, then anything else.
 */
object CaptionTrackSelector {
    const val FALLBACK_LANGUAGE = "en"

    fun order(tracks: List<CaptionTrack>, preferredLanguage: String?): List<CaptionTrack> {
        val usable = tracks.filter { it.url.isNotBlank() }
        val preferred = primary(preferredLanguage) ?: FALLBACK_LANGUAGE
        val buckets: List<(CaptionTrack) -> Boolean> = listOf(
            { !it.autoGenerated && primary(it.language) == preferred },
            { it.autoGenerated && primary(it.language) == preferred },
            { !it.autoGenerated && primary(it.language) == FALLBACK_LANGUAGE },
            { it.autoGenerated && primary(it.language) == FALLBACK_LANGUAGE },
            { !it.autoGenerated },
            { it.autoGenerated }
        )
        val result = LinkedHashSet<CaptionTrack>()
        for (bucket in buckets) {
            usable.filter(bucket)
                // prefer an exact regional match, e.g. en-GB for an en-GB reader
                .sortedByDescending { it.language.equals(preferredLanguage, ignoreCase = true) }
                .forEach { result += it }
        }
        return result.toList()
    }

    fun primary(languageTag: String?): String? = languageTag
        ?.trim()
        ?.takeIf { it.isNotEmpty() }
        ?.split('-', '_')
        ?.first()
        ?.lowercase(Locale.ROOT)
}
