package com.github.libretube.reader.api

import com.github.libretube.reader.model.ArticleContent
import com.github.libretube.reader.model.ArticleSection
import com.github.libretube.reader.model.ReaderErrorKind
import com.github.libretube.reader.model.ReaderException
import com.github.libretube.reader.model.TranscriptRecord
import com.github.libretube.reader.model.TranscriptSource
import com.github.libretube.reader.model.TranscriptText

/**
 * Validates service responses before anything is saved. Content is kept as plain text; nothing is
 * ever interpreted as HTML.
 */
object ArticleValidator {
    const val MAX_SECTIONS = 300
    const val MAX_TEXT_CHARS = 600_000
    const val AI_TRANSCRIPTION_SOURCE = "ai-transcription"

    fun validateArticle(response: ArticleResponseDto): Pair<ArticleContent, String> {
        val body = response.article ?: invalid("missing article")
        val title = body.title?.trim().orEmpty()
        if (title.isEmpty()) invalid("missing title")

        val rawSections = body.sections ?: invalid("missing sections")
        if (rawSections.size > MAX_SECTIONS) invalid("too many sections")
        val sections = rawSections.mapNotNull { section ->
            val paragraphs = section.paragraphs.orEmpty().map { it.trim() }.filter { it.isNotEmpty() }
            if (paragraphs.isEmpty()) return@mapNotNull null
            ArticleSection(heading = section.heading?.trim().orEmpty(), paragraphs = paragraphs)
        }
        if (sections.isEmpty()) invalid("no section has text")

        val visualNotes = body.visualNotes.orEmpty().map { it.trim() }.filter { it.isNotEmpty() }
        val totalChars = title.length + visualNotes.sumOf { it.length } +
            sections.sumOf { s -> s.heading.length + s.paragraphs.sumOf { it.length } }
        if (totalChars > MAX_TEXT_CHARS) invalid("article too large")

        val model = response.model?.trim()?.takeIf { it.isNotEmpty() } ?: "unknown"
        return ArticleContent(title, sections, visualNotes) to model
    }

    fun validateTranscript(
        videoId: String,
        response: TranscriptResponseDto,
        retrievedAtMs: Long
    ): TranscriptRecord {
        if (response.source != AI_TRANSCRIPTION_SOURCE) invalid("unexpected transcript source")
        val segments = TranscriptText.untimedSegments(response.transcript.orEmpty())
        if (segments.isEmpty()) {
            throw ReaderException(ReaderErrorKind.NO_TRANSCRIPT, "The transcription was empty.")
        }
        return TranscriptRecord(
            videoId = videoId,
            title = response.title?.trim().orEmpty(),
            creator = response.creator?.trim().orEmpty(),
            language = response.language?.trim()?.takeIf { it.isNotEmpty() },
            source = TranscriptSource.AI_TRANSCRIPTION,
            autoGenerated = true,
            segments = segments,
            model = response.model?.trim()?.takeIf { it.isNotEmpty() },
            retrievedAtMs = retrievedAtMs
        )
    }

    private fun invalid(reason: String): Nothing =
        throw ReaderException(ReaderErrorKind.INVALID_RESPONSE, reason)
}
