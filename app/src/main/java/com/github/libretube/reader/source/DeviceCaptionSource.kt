package com.github.libretube.reader.source

import android.util.Log
import com.github.libretube.api.obj.Streams
import com.github.libretube.reader.api.executeBounded
import com.github.libretube.reader.model.TranscriptRecord
import com.github.libretube.reader.model.TranscriptSource
import kotlinx.coroutines.CancellationException
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Deferred
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.SupervisorJob
import kotlinx.coroutines.async
import kotlinx.coroutines.withContext
import kotlinx.coroutines.withTimeoutOrNull
import okhttp3.OkHttpClient
import okhttp3.Request
import java.io.IOException

/** Progress reported while looking for a transcript on the device. */
enum class CaptionStage { LOADING_VIDEO, FETCHING_CAPTIONS }

sealed interface DeviceCaptionResult {
    data class Found(val transcript: TranscriptRecord) : DeviceCaptionResult

    data class Unavailable(
        val reason: Reason,
        val title: String?,
        val creator: String?
    ) : DeviceCaptionResult

    enum class Reason {
        /** Content extraction did not finish in time. */
        SOURCE_TIMEOUT,

        /** Content extraction failed, for example blocked or unavailable video. */
        SOURCE_FAILED,

        /** The video lists no caption tracks. */
        NO_TRACKS,

        /** Tracks were listed but none produced usable text. */
        TRACKS_UNUSABLE
    }
}

fun interface CaptionSource {
    suspend fun obtain(videoId: String, onStage: (CaptionStage) -> Unit): DeviceCaptionResult
}

/**
 * Gets captions on the device with LibreTube's configured content source (full local extraction
 * by default) and decodes them without starting a player.
 */
class DeviceCaptionSource(
    private val loadStreams: suspend (String) -> Streams,
    private val httpClient: OkHttpClient,
    private val preferredLanguage: () -> String?,
    private val clock: () -> Long = System::currentTimeMillis,
    private val extractionTimeoutMs: Long = 45_000,
    private val captionTimeoutMs: Long = 20_000,
    private val maxTracksTried: Int = 4
) : CaptionSource {

    override suspend fun obtain(
        videoId: String,
        onStage: (CaptionStage) -> Unit
    ): DeviceCaptionResult {
        onStage(CaptionStage.LOADING_VIDEO)
        val streams = try {
            boundedExtraction(videoId)
                ?: return DeviceCaptionResult.Unavailable(
                    DeviceCaptionResult.Reason.SOURCE_TIMEOUT, null, null
                )
        } catch (e: CancellationException) {
            throw e
        } catch (e: Exception) {
            Log.w(TAG, "Content extraction failed: ${e.javaClass.simpleName}")
            return DeviceCaptionResult.Unavailable(
                DeviceCaptionResult.Reason.SOURCE_FAILED, null, null
            )
        }

        val title = streams.title
        val creator = streams.uploader
        val tracks = streams.subtitles.mapNotNull { subtitle ->
            CaptionTrack(
                url = subtitle.url ?: return@mapNotNull null,
                mimeType = subtitle.mimeType,
                language = subtitle.code,
                name = subtitle.name,
                autoGenerated = subtitle.autoGenerated == true
            )
        }
        if (tracks.isEmpty()) {
            return DeviceCaptionResult.Unavailable(
                DeviceCaptionResult.Reason.NO_TRACKS, title, creator
            )
        }

        onStage(CaptionStage.FETCHING_CAPTIONS)
        val ordered = CaptionTrackSelector.order(tracks, preferredLanguage())
        for (track in ordered.take(maxTracksTried)) {
            val cues = fetchCues(track) ?: continue
            val segments = withContext(Dispatchers.Default) {
                TranscriptNormalizer.normalize(cues, rollingCaptions = track.autoGenerated)
            }
            if (segments.isEmpty()) continue
            val transcript = TranscriptRecord(
                videoId = videoId,
                title = title,
                creator = creator,
                language = track.language,
                source = if (track.autoGenerated) {
                    TranscriptSource.AUTOMATIC_CAPTIONS
                } else {
                    TranscriptSource.CREATOR_CAPTIONS
                },
                autoGenerated = track.autoGenerated,
                segments = segments,
                retrievedAtMs = clock()
            )
            if (transcript.plainText().isBlank()) continue
            return DeviceCaptionResult.Found(transcript)
        }
        return DeviceCaptionResult.Unavailable(
            DeviceCaptionResult.Reason.TRACKS_UNUSABLE, title, creator
        )
    }

    /**
     * The upstream extractor blocks an IO thread and does not respond to cancellation. It runs in
     * a detached scope so the caller can time out or be cancelled immediately; a late result is
     * discarded with the abandoned [Deferred].
     *
     * @return null on timeout
     */
    private suspend fun boundedExtraction(videoId: String): Streams? {
        val deferred = extractionScope.async { loadStreams(videoId) }
        try {
            return withTimeoutOrNull(extractionTimeoutMs) { deferred.await() }
                .also { if (it == null) deferred.cancel() }
        } catch (e: CancellationException) {
            deferred.cancel()
            throw e
        }
    }

    /** @return decoded cues, or null when this track is unusable */
    private suspend fun fetchCues(track: CaptionTrack): List<RawCue>? {
        val request = try {
            Request.Builder().url(track.url).get().build()
        } catch (e: IllegalArgumentException) {
            return null
        }
        val result = try {
            withTimeoutOrNull(captionTimeoutMs) {
                httpClient.newCall(request).executeBounded(MAX_CAPTION_BYTES)
            } ?: return null
        } catch (e: CancellationException) {
            throw e
        } catch (e: IOException) {
            return null
        }
        if (!result.isSuccessful) return null
        if (CaptionPayload.problem(result.body, result.contentType) != null) return null

        val mimeType = CaptionPayload.resolveMimeType(track.mimeType, result.body) ?: return null
        return try {
            withContext(Dispatchers.Default) {
                CaptionParser.parse(result.body, mimeType)?.takeIf { cues ->
                    cues.any { it.text.isNotBlank() }
                }
            }
        } catch (e: CancellationException) {
            throw e
        } catch (e: Exception) {
            // malformed caption data counts as an unusable track
            null
        }
    }

    companion object {
        private const val TAG = "DeviceCaptionSource"
        private const val MAX_CAPTION_BYTES = 8L * 1024 * 1024

        private val extractionScope = CoroutineScope(SupervisorJob() + Dispatchers.IO)
    }
}
