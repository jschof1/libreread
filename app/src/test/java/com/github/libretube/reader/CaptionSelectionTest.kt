package com.github.libretube.reader

import com.github.libretube.reader.source.CaptionPayload
import com.github.libretube.reader.source.CaptionTrack
import com.github.libretube.reader.source.CaptionTrackSelector
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Test

class CaptionSelectionTest {
    private fun track(lang: String, auto: Boolean, url: String = "https://x/$lang/$auto") =
        CaptionTrack(url, "text/vtt", lang, lang, auto)

    @Test
    fun `prefers creator then automatic captions in the preferred language, then English`() {
        val tracks = listOf(
            track("en", auto = true),
            track("de", auto = true),
            track("fr", auto = false),
            track("en", auto = false),
            track("de", auto = false)
        )
        val ordered = CaptionTrackSelector.order(tracks, "de-DE")
        assertEquals(
            listOf("de" to false, "de" to true, "en" to false, "en" to true, "fr" to false),
            ordered.map { it.language to it.autoGenerated }
        )
    }

    @Test
    fun `prefers the exact regional variant within a language`() {
        val tracks = listOf(track("en-US", false), track("en-GB", false))
        assertEquals("en-GB", CaptionTrackSelector.order(tracks, "en-GB").first().language)
    }

    @Test
    fun `skips tracks without a URL and falls back to English when no preference`() {
        val tracks = listOf(track("es", false), track("en", true), track("en", false, url = " "))
        val ordered = CaptionTrackSelector.order(tracks, null)
        assertEquals(listOf("en" to true, "es" to false), ordered.map { it.language to it.autoGenerated })
    }

    @Test
    fun `empty and HTML responses count as unavailable`() {
        assertEquals(CaptionPayload.Problem.EMPTY, CaptionPayload.problem(ByteArray(0), "text/vtt"))
        assertEquals(CaptionPayload.Problem.EMPTY, CaptionPayload.problem("  \n".toByteArray(), null))
        assertEquals(
            CaptionPayload.Problem.HTML,
            CaptionPayload.problem("<!DOCTYPE html><html>consent</html>".toByteArray(), "text/plain")
        )
        assertEquals(CaptionPayload.Problem.HTML, CaptionPayload.problem("x".toByteArray(), "text/html; charset=utf-8"))
        assertNull(CaptionPayload.problem("WEBVTT\n\n".toByteArray(), "text/vtt"))
    }

    @Test
    fun `resolves MIME type from declaration or content`() {
        val vtt = "﻿WEBVTT\n\n00:00.000 --> 00:01.000\nhi".toByteArray()
        assertEquals(CaptionPayload.MIME_VTT, CaptionPayload.resolveMimeType(null, vtt))
        assertEquals(CaptionPayload.MIME_TTML, CaptionPayload.resolveMimeType("application/ttml+xml; charset=UTF-8", vtt))
        val ttml = """<?xml version="1.0"?><tt xmlns="http://www.w3.org/ns/ttml"><body/></tt>""".toByteArray()
        assertEquals(CaptionPayload.MIME_TTML, CaptionPayload.resolveMimeType("text/xml", ttml))
        val srt = "1\n00:00:01,000 --> 00:00:02,000\nhi\n".toByteArray()
        assertEquals(CaptionPayload.MIME_SUBRIP, CaptionPayload.resolveMimeType(null, srt))
        assertEquals("text/xml", CaptionPayload.resolveMimeType("text/xml", "<timedtext/>".toByteArray()))
    }
}
